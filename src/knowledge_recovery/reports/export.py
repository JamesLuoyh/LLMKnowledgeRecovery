"""JSON, CSV, and generated LaTeX for a saved evaluation.

The LaTeX fragment is meant to be included with ``\\input``. Computed
numbers are written from the report. They are not copied into source prose.
"""

from __future__ import annotations

import csv
import json
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any


def export_report(report: Mapping[str, Any], directory: Path | str) -> dict[str, Path]:
    """Write ``report.json``, ``metrics.csv``, and ``metrics.tex``."""
    target = Path(directory)
    if not target.is_absolute():
        raise ValueError("reports are written under an absolute storage directory")
    target.mkdir(parents=True, exist_ok=True)
    json_path = target / "report.json"
    csv_path = target / "metrics.csv"
    tex_path = target / "metrics.tex"
    json_path.write_text(json.dumps(report, allow_nan=False, indent=2, sort_keys=True) + "\n")
    rows = list(iter_metric_rows(report))
    with csv_path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    tex_path.write_text(_latex(rows))
    return {"json": json_path, "csv": csv_path, "latex": tex_path}


def iter_metric_rows(report: Mapping[str, Any]) -> tuple[dict[str, Any], ...]:
    """One record per pooled, per-variant, and per-position test slice."""
    rows: list[dict[str, Any]] = []
    for task_id, methods in report["test_metrics"].items():
        for method_id, block in methods.items():
            for domain, domain_block in block["domains"].items():
                rows.append(_metric_row(task_id, method_id, domain, "pooled", "pooled", block["selected_layer"], domain_block["pooled"]))
                for name, metrics in domain_block["by_variant"].items():
                    rows.append(_metric_row(task_id, method_id, domain, name, "variant", block["selected_layer"], metrics))
                for name, metrics in domain_block["by_position"].items():
                    rows.append(_metric_row(task_id, method_id, domain, name, "position", block["selected_layer"], metrics))
    return tuple(rows)


def _metric_row(
    task_id: str,
    method_id: str,
    domain: str,
    population: str,
    population_kind: str,
    selected_layer: int | None,
    metrics: Mapping[str, Any],
) -> dict[str, Any]:
    return {
        "task": task_id,
        "method": method_id,
        "domain": domain,
        "population": population,
        "population_kind": population_kind,
        "selected_layer": "" if selected_layer is None else selected_layer,
        "count": metrics["count"],
        "cross_entropy": metrics["cross_entropy"],
        "brier": metrics["brier"],
        "k": metrics["mean_true_class_probability"],
        "ece": metrics["ece"],
    }


def _latex(rows: Sequence[Mapping[str, Any]]) -> str:
    lines = [
        "% generated by knowledge_recovery.reports.export",
        "\\begin{tabular}{llllrrrr}",
        "task & method & domain & population & CE & Brier & $K$ & ECE \\\\",
        "\\hline",
    ]
    for row in rows:
        lines.append(
            " & ".join((
                _tex(row["task"]),
                _tex(row["method"]),
                _tex(row["domain"]),
                _tex(row["population"]),
                _number(row["cross_entropy"]),
                _number(row["brier"]),
                _number(row["k"]),
                _number(row["ece"]),
            ))
            + " \\\\"
        )
    lines.append("\\end{tabular}")
    return "\n".join(lines) + "\n"


def _tex(value: object) -> str:
    text = str(value)
    return text.replace("\\", "\\textbackslash{}").replace("_", "\\_").replace("&", "\\&").replace("%", "\\%")


def _number(value: object) -> str:
    if value is None or value == "":
        return "---"
    return json.dumps(value)
